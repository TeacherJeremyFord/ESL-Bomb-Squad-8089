"""Regenerate VOCAB_TRACKER.md from the module design docs in this folder.

Each module doc (M*.md) declares its words on one line near the top:

    **Target vocab (24):** grandfather, grandmother, father, ...

Words must be canonical entries (or listed aliases) from vocab_260.tsv.
The count in parentheses must match the number of words listed.

Usage:
    python docs/design/modules/vocab_tracker.py          # rewrite VOCAB_TRACKER.md
    python docs/design/modules/vocab_tracker.py --check  # exit 1 if stale or invalid
"""

from __future__ import annotations

import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORD_LIST = HERE / "vocab_260.tsv"
TRACKER = HERE / "VOCAB_TRACKER.md"
VOCAB_LINE = re.compile(r"^\*\*Target vocab \((\d+)\):\*\*\s*(.+)$", re.MULTILINE)
TITLE_LINE = re.compile(r"^# (.+)$", re.MULTILINE)


def load_words() -> tuple[list[dict], dict[str, str]]:
    with WORD_LIST.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    lookup: dict[str, str] = {}
    for row in rows:
        lookup[row["word"].lower()] = row["word"]
        for alias in filter(None, row["aliases"].split("|")):
            lookup[alias.lower()] = row["word"]
    return rows, lookup


def load_modules(lookup: dict[str, str]) -> tuple[list[dict], list[str]]:
    modules, errors = [], []
    for path in sorted(HERE.glob("M*.md")):
        text = path.read_text(encoding="utf-8")
        match = VOCAB_LINE.search(text)
        if not match:
            errors.append(f"{path.name}: no '**Target vocab (N):**' line")
            continue
        declared = int(match.group(1))
        listed = [w.strip() for w in match.group(2).split(",") if w.strip()]
        words = []
        for w in listed:
            canonical = lookup.get(w.lower())
            if canonical is None:
                errors.append(f"{path.name}: '{w}' is not on the 260-word list")
            elif canonical in words:
                errors.append(f"{path.name}: '{w}' listed twice")
            else:
                words.append(canonical)
        if declared != len(listed):
            errors.append(f"{path.name}: header says {declared} words, lists {len(listed)}")
        title = TITLE_LINE.search(text)
        modules.append({
            "file": path.name,
            "title": title.group(1) if title else path.stem,
            "words": words,
        })
    return modules, errors


def render(rows: list[dict], modules: list[dict]) -> str:
    used_by: dict[str, list[str]] = defaultdict(list)
    for m in modules:
        for w in m["words"]:
            used_by[w].append(m["file"].split("_")[0])

    used = [r for r in rows if r["word"] in used_by]
    needed = [r for r in rows if r["word"] not in used_by]
    out = [
        "# Vocab Tracker: 260-Word List",
        "",
        "<!-- GENERATED by vocab_tracker.py; do not edit by hand. -->",
        "",
        f"**Used: {len(used)} / {len(rows)}** · **Still needed: {len(needed)}** "
        f"· Modules: {len(modules)}",
        "",
        "## Still needed",
        "",
    ]
    if not needed:
        out.append("All 260 words are used by at least one module.")
    else:
        by_cat: dict[str, list[str]] = defaultdict(list)
        for r in needed:
            by_cat[r["category"]].append(r["word"])
        for cat, words in by_cat.items():
            out.append(f"- **{cat}** ({len(words)}): {', '.join(words)}")
    out += ["", "## Modules", "", "| Module | Words |", "|---|---|"]
    for m in modules:
        out.append(f"| [{m['title']}]({m['file']}) | {len(m['words'])} |")
    out += [
        "",
        "## Used (word → modules)",
        "",
        "Words used by only one module are good candidates to recycle in later designs.",
        "",
        "| # | Word | 中文 | Category | Modules |",
        "|---|---|---|---|---|",
    ]
    for r in used:
        out.append(
            f"| {r['id']} | {r['word']} | {r['zh']} | {r['category']} | "
            f"{', '.join(used_by[r['word']])} |"
        )
    return "\n".join(out) + "\n"


def main() -> int:
    rows, lookup = load_words()
    modules, errors = load_modules(lookup)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    content = render(rows, modules)
    if "--check" in sys.argv:
        stale = not TRACKER.exists() or TRACKER.read_text(encoding="utf-8") != content
        if stale:
            print("VOCAB_TRACKER.md is out of date; rerun vocab_tracker.py", file=sys.stderr)
        return 1 if errors or stale else 0
    TRACKER.write_text(content, encoding="utf-8")
    used = sum(1 for r in rows if any(r["word"] in m["words"] for m in modules))
    print(f"Wrote {TRACKER.name}: {used}/{len(rows)} used, {len(modules)} modules")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
